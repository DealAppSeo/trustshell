#!/usr/bin/env node
/**
 * T4 A4 — regenerate docs/SDK_HONEST_RETURN_TYPES.md FROM the TypeScript interfaces.
 * Drift is a test failure, not a review comment.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const SRC = resolve(process.cwd(), 'src/lib/trustshell.ts');
const OUT = resolve(process.cwd(), 'docs/SDK_HONEST_RETURN_TYPES.md');

function fieldsOf(src, name) {
  const re = new RegExp(`export interface ${name}\\s*\\{([\\s\\S]*?)\\n\\}`);
  const m = src.match(re);
  if (!m) throw new Error(`interface ${name} not found`);
  const body = m[1];
  const fields = [];
  for (const line of body.split('\n')) {
    const f = line.match(/^\s*(?:\/\*\*[\s\S]*?\*\/\s*)?([A-Za-z_][A-Za-z0-9_]*)\??:/);
    const simple = line.match(/^\s+([A-Za-z_][A-Za-z0-9_]*)\??:/);
    if (simple) fields.push(simple[1]);
  }
  return [...new Set(fields)];
}

const src = readFileSync(SRC, 'utf8');
const verify = fieldsOf(src, 'VerifyOutputResult');
const repid = fieldsOf(src, 'RepIDResult');
const proof = fieldsOf(src, 'ProofPresentation');

const required = {
  VerifyOutputResult: ['verdict', 'grounding', 'providersUsed', 'providers_used', 'evidence'],
  RepIDResult: ['repid', 'tier', 'minted', 'signer', 'scoreLane', 'reasons'],
  ProofPresentation: ['signer', 'note', 'reasons'],
};

for (const [iface, need] of Object.entries(required)) {
  const have = iface === 'VerifyOutputResult' ? verify : iface === 'RepIDResult' ? repid : proof;
  for (const n of need) {
    if (!have.includes(n)) {
      console.error(`MISSING field ${n} on ${iface}`);
      process.exit(1);
    }
  }
}

function table(fields) {
  return ['| field | in types |', '|---|---|', ...fields.map((f) => `| \`${f}\` | yes |`)].join('\n');
}

const md = `# SDK honest return types (generated — LOOP T4)

Do not edit this file by hand. Run \`node scripts/gen-honest-return-docs.mjs\`.
A return type that carries its own evidence cannot lie, and then the docs cannot drift from it.

## \`verifyOutput\` → \`VerifyOutputResult\`
${table(verify)}

\`providers_used\` / \`providersUsed\` is the **measured** quorum (\`evidence.length\`), never a constant.

## \`getRepID\` → \`RepIDResult\`
${table(repid)}

A null field always carries a reason in \`reasons\`. Never omitted, never defaulted.

## \`presentProof\` → \`ProofPresentation\`
${table(proof)}

\`note\` is the fixed honest label \`'not a registry aggregate'\`.
`;

writeFileSync(OUT, md);
console.log(`wrote ${OUT} (${verify.length}+${repid.length}+${proof.length} fields)`);
