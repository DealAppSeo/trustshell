#!/usr/bin/env node
/** trustshell check — api.github.com only. No account. Optional GITHUB_TOKEN. */
'use strict';
const { writeFileSync } = require('node:fs');

function parseRun(url) {
  const m = String(url || '').match(/github\.com\/([^/]+)\/([^/]+)\/actions\/runs\/(\d+)/);
  if (!m) return null;
  return { owner: m[1], repo: m[2], runId: m[3] };
}

async function gh(path, token) {
  const headers = { 'User-Agent': 'trustshell-check', Accept: 'application/vnd.github+json' };
  if (token) headers.Authorization = 'Bearer ' + token;
  const res = await fetch('https://api.github.com' + path, { headers });
  const text = await res.text();
  let body;
  try { body = JSON.parse(text); } catch { body = { raw: text }; }
  return { ok: res.ok, status: res.status, body };
}

function line(ok, label, detail) {
  const mark = ok === true ? '\u2713' : ok === false ? '\u2715' : '?';
  return mark + '  ' + label + (detail ? '\n    ' + detail : '');
}

async function main() {
  const url = process.argv[2];
  const json = process.argv.includes('--json');
  if (!url || url === '-h' || url === '--help') {
    process.stderr.write('usage: node bin/check.js <github-actions-run-url> [--json]\n');
    process.exit(2);
  }
  const parsed = parseRun(url);
  if (!parsed) {
    process.stderr.write('error: need https://github.com/owner/repo/actions/runs/123\n');
    process.exit(2);
  }
  const token = process.env.GITHUB_TOKEN || '';
  const run = await gh('/repos/' + parsed.owner + '/' + parsed.repo + '/actions/runs/' + parsed.runId, token);
  if (!run.ok) {
    process.stderr.write('GitHub ' + run.status + ': ' + ((run.body && run.body.message) || 'failed') + '\n');
    process.exit(3);
  }
  const jobs = await gh('/repos/' + parsed.owner + '/' + parsed.repo + '/actions/runs/' + parsed.runId + '/jobs', token);
  const jobList = (jobs.body && jobs.body.jobs) || [];
  const failed = jobList.filter((j) => j.conclusion && j.conclusion !== 'success' && j.conclusion !== 'skipped');
  const runOk = run.body.conclusion === 'success';
  const jobsOk = failed.length === 0 && jobList.length > 0;
  let verdict = 'COMPLETE';
  if (runOk && !jobsOk) verdict = 'INCONSISTENT';
  else if (!runOk) verdict = 'FAILED';
  else if (!jobs.ok) verdict = 'INCONCLUSIVE';
  const sha = run.body.head_sha || '';
  const checks = [
    line(true, 'A workflow run with this id exists', (run.body.name || '') + ' \u00b7 ' + run.body.status),
    line(run.body.status === 'completed', 'The run finished', 'status: ' + run.body.status),
    line(runOk, 'The run succeeded', 'GitHub reports conclusion: ' + run.body.conclusion),
    line(jobsOk, 'Every job in the run passed', failed.length ? failed.length + ' of ' + jobList.length + ' jobs did not pass: ' + failed.map((j) => j.name).join(', ') : jobList.length + ' jobs'),
    line(Boolean(sha), 'The commit exists on the remote', sha),
  ];
  const does_not_prove = [
    'This is what GitHub can confirm. It is not a judgement about whether the code is correct.',
    'It cannot show work done outside this repository, or on a branch that was never pushed.',
    'A passing test suite proves the tests that exist passed — not that the right tests exist.',
    'It does not establish who or what authored the change.',
  ];
  if (json) {
    process.stdout.write(JSON.stringify({ verdict, source: url, freshness: 'LIVE', host: 'api.github.com', does_not_prove }, null, 2) + '\n');
    return;
  }
  const title = (run.body.display_title) || '';
  const text = [
    'TrustShell \u00b7 check',
    title,
    parsed.owner + '/' + parsed.repo + ' \u00b7 ' + (run.body.head_branch || '') + ' \u00b7 ' + sha.slice(0, 12),
    url,
    '',
    verdict + '  \u00b7  checked live',
    '',
    ...checks,
    '',
    'What this does not prove',
    ...does_not_prove.map((s) => '* ' + s),
    '',
    'Generated by trustshell check \u00b7 public github API \u00b7 nothing uploaded',
  ].join('\n');
  process.stdout.write(text + '\n');
  try { writeFileSync('trustshell-card.txt', text); } catch (_) {}
}

main().catch((e) => { process.stderr.write(String(e && e.stack || e) + '\n'); process.exit(3); });
